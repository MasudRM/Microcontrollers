#include<avr/io.h>
#include <util/delay.h>

void main(void)
{
	DDRC |=((1<<0) | (1<<1) | (1<<2) | (1<<3) | (1<<4) | (1<<5) | (1<<6) | (1<<7));
	DDRB |=((1<<0) | (1<<1) | (1<<2) | (1<<3) | (1<<4) | (1<<5) | (1<<6) | (1<<7));
	DDRD &=~((1<<2)|(1<<3));
	
	char seg[11] = {0b00111111, 0b00000110, 0b01011011, 0b01001111, 0b01100110, 0b01101101, 0b01111101, 0b00000111,0b01111111, 0b01101111, 0b10000000};
	
	while(1)
	{
		for(int i=0; i<=10; i++)
		{
			PORTB =seg[i];
			_delay_ms(500);
		
		}
	
	}






}
